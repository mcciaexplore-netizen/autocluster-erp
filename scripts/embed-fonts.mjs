// Regenerates lib/pdf/fonts.generated.ts from the files in assets/fonts.
// The PDF code imports the fonts from that module, so they are bundled with the
// server code and never read from a file path at runtime.
//   node scripts/embed-fonts.mjs
import fs from "node:fs";
import path from "node:path";

const dir = path.join(import.meta.dirname, "..", "assets", "fonts");
const files = {
  outfit400: "outfit-latin-400-normal.woff",
  outfit500: "outfit-latin-500-normal.woff",
  outfit600: "outfit-latin-600-normal.woff",
  dmSerif400: "dm-serif-display-latin-400-normal.woff",
  rupee400: "noto-sans-latin-ext-400-normal.woff",
  rupee600: "noto-sans-latin-ext-600-normal.woff",
};
let out = "// Generated by scripts/embed-fonts.mjs. Do not edit by hand.\n// Fonts: Outfit, DM Serif Display, Noto Sans (all SIL Open Font License).\n\n";
for (const [name, file] of Object.entries(files)) {
  const b64 = fs.readFileSync(path.join(dir, file)).toString("base64");
  out += `export const ${name} = "data:font/woff;base64,${b64}";\n`;
}
fs.writeFileSync(path.join(import.meta.dirname, "..", "lib", "pdf", "fonts.generated.ts"), out);
console.log("Wrote lib/pdf/fonts.generated.ts");
